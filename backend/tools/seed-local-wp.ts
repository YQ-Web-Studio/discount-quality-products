import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';

export interface FixtureProduct {
  name: string;
  slug: string;
  regular_price: string;
  category_slug: string;
  stock_quantity: number;
  manage_stock: boolean;
  status: string;
  tags?: string[];
  meta_data?: Array<{ key: string; value: string }>;
}

export interface FixtureCategory {
  name: string;
  slug: string;
}

export interface FixtureCoupon {
  code: string;
  amount: string;
  discount_type: string;
  description: string;
  usage_limit_per_user?: number;
  usage_limit?: number;
  minimum_amount?: string;
  date_expires?: string;
}

export interface FixtureData {
  categories: FixtureCategory[];
  products: FixtureProduct[];
  coupons: FixtureCoupon[];
}

export function buildProductCliArgs(product: FixtureProduct, categoryIdMap: Record<string, number>): string[] {
  const args: string[] = [
    `--name=${product.name}`,
    `--slug=${product.slug}`,
    `--type=simple`,
    `--regular_price=${product.regular_price}`,
    `--manage_stock=${product.manage_stock}`,
    `--stock_quantity=${product.stock_quantity}`,
    `--status=${product.status}`,
    '--user=admin',
  ];

  const catId = categoryIdMap[product.category_slug];
  if (catId) {
    args.push(`--categories=${JSON.stringify([{ id: catId }])}`);
  }

  if (product.tags && product.tags.length > 0) {
    const tagsPayload = product.tags.map((t) => ({ name: t }));
    args.push(`--tags=${JSON.stringify(tagsPayload)}`);
  }

  if (product.meta_data && product.meta_data.length > 0) {
    args.push(`--meta_data=${JSON.stringify(product.meta_data)}`);
  }

  return args;
}

export function buildCouponCliArgs(coupon: FixtureCoupon): string[] {
  const args: string[] = [
    `--code=${coupon.code}`,
    `--amount=${coupon.amount}`,
    `--discount_type=${coupon.discount_type}`,
    `--description=${coupon.description}`,
    '--user=admin',
  ];

  if (coupon.usage_limit_per_user !== undefined) {
    args.push(`--usage_limit_per_user=${coupon.usage_limit_per_user}`);
  }

  if (coupon.usage_limit !== undefined) {
    args.push(`--usage_limit=${coupon.usage_limit}`);
  }

  if (coupon.minimum_amount !== undefined) {
    args.push(`--minimum_amount=${coupon.minimum_amount}`);
  }

  if (coupon.date_expires !== undefined) {
    args.push(`--date_expires=${coupon.date_expires}`);
  }

  return args;
}

export function buildApiKeyPhpScript(consumerKey: string, consumerSecret: string, description = 'Local Test Key'): string {
  return `global $wpdb; $table = $wpdb->prefix . 'woocommerce_api_keys'; $hashed_key = wc_api_hash('${consumerKey}'); $wpdb->replace($table, array('user_id' => 1, 'description' => '${description}', 'permissions' => 'read_write', 'consumer_key' => $hashed_key, 'consumer_secret' => '${consumerSecret}', 'truncated_key' => substr('${consumerKey}', -7)), array('%d', '%s', '%s', '%s', '%s', '%s'));`;
}

export function buildEnvTestLocalContent(config: {
  wpUrl: string;
  consumerKey: string;
  consumerSecret: string;
  stripeWebhookSecret?: string;
}): string {
  const webhookSecret = config.stripeWebhookSecret || 'whsec_test_secret';
  return [
    `# Local Test Environment Variables (Auto-generated by seed-local-wp)`,
    `NEXT_PUBLIC_WORDPRESS_URL=${config.wpUrl}`,
    `WOOCOMMERCE_URL=${config.wpUrl}`,
    `WC_CONSUMER_KEY=${config.consumerKey}`,
    `WC_CONSUMER_SECRET=${config.consumerSecret}`,
    `STRIPE_WEBHOOK_SECRET=${webhookSecret}`,
    '',
  ].join('\n');
}

export function writeEnvTestLocal(
  targetPath: string,
  config: {
    wpUrl: string;
    consumerKey: string;
    consumerSecret: string;
    stripeWebhookSecret?: string;
  }
): void {
  const content = buildEnvTestLocalContent(config);
  fs.writeFileSync(targetPath, content, 'utf8');
}

function runWpCli(command: string): string {
  return execSync(`npx wp-env run cli ${command}`, {
    encoding: 'utf8',
    stdio: ['pipe', 'pipe', 'pipe'],
  });
}

export async function seedLocalEnvironment(): Promise<void> {
  const wpUrl = process.env.LOCAL_WP_URL || 'http://localhost:8888';
  const consumerKey = process.env.LOCAL_WC_KEY || 'ck_local_test';
  const consumerSecret = process.env.LOCAL_WC_SECRET || 'cs_local_test';

  console.log(`[seed-local-wp] Target Environment: ${wpUrl}`);

  const fixturePath = path.resolve(__dirname, '../fixtures/seed-catalog.json');
  if (!fs.existsSync(fixturePath)) {
    throw new Error(`Fixture file not found: ${fixturePath}`);
  }

  const catalog: FixtureData = JSON.parse(fs.readFileSync(fixturePath, 'utf8'));
  console.log(`[seed-local-wp] Loaded ${catalog.categories.length} categories, ${catalog.products.length} products, and ${catalog.coupons.length} coupons.`);

  // 1. Verify container connectivity
  try {
    const isInstalled = runWpCli('wp core is-installed');
    console.log('[seed-local-wp] WordPress container is active.');
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : String(err);
    console.warn(`[seed-local-wp] Local WordPress container is not running or accessible via wp-env cli.`);
    console.warn(`[seed-local-wp] Run 'npm run test:env:start' or 'npm run wp:start' to start Docker container.`);
    console.log('[seed-local-wp] Fixtures and environment generators validated.');
    return;
  }

  // 2. Set WooCommerce currency & tax options
  console.log('[seed-local-wp] Configuring WooCommerce settings (GBP, VAT)...');
  try {
    runWpCli('wp option update woocommerce_currency GBP');
    runWpCli('wp option update woocommerce_calc_taxes yes');
    runWpCli('wp option update woocommerce_prices_include_tax no');
  } catch (err) {
    console.warn('[seed-local-wp] Notice configuring options:', err);
  }

  // 3. Inject deterministic API key
  console.log(`[seed-local-wp] Provisioning deterministic REST API key (${consumerKey})...`);
  try {
    const phpScript = buildApiKeyPhpScript(consumerKey, consumerSecret, 'Deterministic Test Key');
    runWpCli(`wp eval "${phpScript}"`);
    console.log('[seed-local-wp] Deterministic API key provisioned.');
  } catch (err) {
    console.warn('[seed-local-wp] Notice provisioning API key:', err);
  }

  // 4. Seed categories
  console.log('[seed-local-wp] Seeding product categories...');
  const categoryIdMap: Record<string, number> = {};
  for (const cat of catalog.categories) {
    try {
      let termIdStr = runWpCli(`wp term list product_cat --slug="${cat.slug}" --field=term_id`).trim();
      if (!termIdStr) {
        termIdStr = runWpCli(`wp term create product_cat "${cat.name}" --slug="${cat.slug}" --porcelain`).trim();
      }
      const termId = parseInt(termIdStr, 10);
      if (!isNaN(termId)) {
        categoryIdMap[cat.slug] = termId;
      }
    } catch {
      // Fallback
    }
  }

  // 5. Seed products
  console.log(`[seed-local-wp] Seeding ${catalog.products.length} products...`);
  for (const prod of catalog.products) {
    try {
      const existingId = runWpCli(`wp post list --post_type=product --name="${prod.slug}" --field=ID`).trim();
      const cliArgs = buildProductCliArgs(prod, categoryIdMap);
      if (!existingId) {
        runWpCli(`wp wc product create ${cliArgs.join(' ')}`);
        console.log(`  + Product created: ${prod.name} (${prod.slug})`);
      } else {
        runWpCli(`wp wc product update ${existingId} ${cliArgs.join(' ')}`);
        console.log(`  ~ Product updated: ${prod.name} (${prod.slug})`);
      }
    } catch (err) {
      console.warn(`[seed-local-wp] Warning seeding product ${prod.slug}:`, err);
    }
  }

  // 6. Seed coupons
  console.log(`[seed-local-wp] Seeding ${catalog.coupons.length} coupons...`);
  for (const coupon of catalog.coupons) {
    try {
      const existingCouponId = runWpCli(`wp post list --post_type=shop_coupon --title="${coupon.code}" --field=ID`).trim();
      const cliArgs = buildCouponCliArgs(coupon);
      if (!existingCouponId) {
        runWpCli(`wp wc shop_coupon create ${cliArgs.join(' ')}`);
        console.log(`  + Coupon created: ${coupon.code}`);
      } else {
        runWpCli(`wp wc shop_coupon update ${existingCouponId} ${cliArgs.join(' ')}`);
        console.log(`  ~ Coupon updated: ${coupon.code}`);
      }
    } catch (err) {
      console.warn(`[seed-local-wp] Warning seeding coupon ${coupon.code}:`, err);
    }
  }

  // 7. Write .env.test.local file
  const envTestLocalPath = path.resolve(process.cwd(), '.env.test.local');
  writeEnvTestLocal(envTestLocalPath, {
    wpUrl,
    consumerKey,
    consumerSecret,
    stripeWebhookSecret: 'whsec_test_secret',
  });
  console.log(`[seed-local-wp] Generated local test environment configuration at: ${envTestLocalPath}`);
  console.log('[seed-local-wp] Seeding complete! Environment is ready.');
}

// Execute when run directly
if (require.main === module || process.argv[1]?.includes('seed-local-wp')) {
  seedLocalEnvironment().catch((err) => {
    console.error('[seed-local-wp] Fatal error:', err);
    process.exit(1);
  });
}
